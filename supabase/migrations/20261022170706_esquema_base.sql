-- Esquema base de Cívika (ADR-1, ADR-2, ADR-12).
-- PostgreSQL 17 + PostGIS. Las migraciones son la única fuente del esquema.

create schema if not exists extensions;
create extension if not exists postgis with schema extensions;

-- Enums del dominio. El rol SISTEMA no existe en la base: lo representan las
-- funciones y triggers que ejecutan cambios automáticos.
create type public.rol as enum ('ciudadano', 'moderador', 'entidad');
create type public.estado as enum ('reportado', 'en_revision', 'derivado', 'en_atencion', 'resuelto', 'rechazado');
create type public.tipo_zona as enum ('campus', 'distrito');
create type public.tipo_reporte as enum ('original', 'apoyo');
create type public.visibilidad as enum ('publico', 'interno');

create sequence public.incidentes_codigo_seq start with 1;

create table public.entidades (
    id integer generated by default as identity primary key,
    nombre text not null unique,
    tipo text not null
);

create table public.zonas (
    id integer generated by default as identity primary key,
    nombre text not null unique,
    tipo public.tipo_zona not null,
    ubigeo text,
    geom extensions.geometry(MultiPolygon, 4326) not null,
    constraint zonas_geom_valida check (extensions.ST_IsValid(geom))
);

create table public.categorias (
    id integer generated by default as identity primary key,
    service_code text not null unique,
    nombre text not null,
    peso_prioridad integer not null check (peso_prioridad >= 0),
    radio_duplicado_m integer not null check (radio_duplicado_m > 0),
    ventana_dias integer not null check (ventana_dias > 0),
    plazo_objetivo_dias integer not null check (plazo_objetivo_dias > 0),
    activa boolean not null default true
);

create table public.usuarios (
    id uuid primary key,
    nombre text not null,
    zona_id integer references public.zonas(id),
    rol public.rol not null default 'ciudadano',
    entidad_id integer references public.entidades(id),
    activo boolean not null default true,
    constraint usuarios_entidad_coherente check (
        (rol = 'entidad' and entidad_id is not null)
        or (rol <> 'entidad' and entidad_id is null)
    )
);

create table public.reglas_ruteo (
    categoria_id integer not null references public.categorias(id) on delete cascade,
    zona_id integer not null references public.zonas(id) on delete cascade,
    entidad_id integer not null references public.entidades(id),
    primary key (categoria_id, zona_id)
);

create table public.incidentes (
    id uuid primary key default gen_random_uuid(),
    codigo text not null unique,
    categoria_id integer not null references public.categorias(id),
    zona_id integer not null references public.zonas(id),
    entidad_id integer references public.entidades(id),
    duplicado_de uuid references public.incidentes(id),
    geom extensions.geography(Point, 4326) not null,
    direccion text,
    status public.estado not null default 'reportado',
    prioridad integer not null default 0,
    apoyos_count integer not null default 0 check (apoyos_count >= 0),
    version integer not null default 0,
    creado_en timestamptz not null default now()
);

create table public.reportes (
    id uuid primary key default gen_random_uuid(),
    usuario_id uuid not null references public.usuarios(id),
    cliente_id uuid not null,
    incidente_id uuid not null references public.incidentes(id) on delete cascade,
    tipo public.tipo_reporte not null default 'original',
    descripcion text,
    geom extensions.geography(Point, 4326) not null,
    categoria_sugerida integer references public.categorias(id),
    confianza real check (confianza is null or (confianza >= 0 and confianza <= 1)),
    ubicacion_simulada boolean not null default false,
    creado_en timestamptz not null default now(),
    unique (usuario_id, cliente_id)
);

create table public.fotos (
    id uuid primary key default gen_random_uuid(),
    reporte_id uuid not null references public.reportes(id) on delete cascade,
    storage_path text not null unique,
    oculta boolean not null default false
);

create table public.apoyos (
    usuario_id uuid not null references public.usuarios(id) on delete cascade,
    incidente_id uuid not null references public.incidentes(id) on delete cascade,
    creado_en timestamptz not null default now(),
    primary key (usuario_id, incidente_id)
);

create table public.historial_estados (
    id bigint generated by default as identity primary key,
    incidente_id uuid not null references public.incidentes(id) on delete cascade,
    estado_anterior public.estado,
    estado_nuevo public.estado not null,
    comentario text,
    autor_id uuid references public.usuarios(id) on delete set null,
    creado_en timestamptz not null default now()
);

create table public.denuncias (
    id uuid primary key default gen_random_uuid(),
    reporte_id uuid not null references public.reportes(id) on delete cascade,
    usuario_id uuid not null references public.usuarios(id) on delete cascade,
    motivo text not null,
    resolucion text,
    creado_en timestamptz not null default now()
);

create table public.verificaciones (
    usuario_id uuid not null references public.usuarios(id) on delete cascade,
    incidente_id uuid not null references public.incidentes(id) on delete cascade,
    sigue_resuelto boolean not null,
    creado_en timestamptz not null default now(),
    primary key (usuario_id, incidente_id)
);

create table public.notificaciones (
    id uuid primary key default gen_random_uuid(),
    usuario_id uuid not null references public.usuarios(id) on delete cascade,
    incidente_id uuid references public.incidentes(id) on delete cascade,
    tipo text not null,
    leida boolean not null default false,
    creado_en timestamptz not null default now()
);

create table public.dispositivos (
    fcm_token text primary key,
    usuario_id uuid not null references public.usuarios(id) on delete cascade
);

create table public.auditoria (
    id bigint generated by default as identity primary key,
    actor_id uuid references public.usuarios(id) on delete set null,
    accion text not null,
    objeto text not null,
    antes jsonb,
    despues jsonb,
    creado_en timestamptz not null default now()
);

create table public.comentarios (
    id uuid primary key default gen_random_uuid(),
    incidente_id uuid not null references public.incidentes(id) on delete cascade,
    autor_id uuid not null references public.usuarios(id) on delete cascade,
    visibilidad public.visibilidad not null default 'publico',
    texto text not null check (length(trim(texto)) between 1 and 2000),
    creado_en timestamptz not null default now()
);

create table public.consentimientos (
    usuario_id uuid not null references public.usuarios(id) on delete cascade,
    version_politica text not null,
    aceptado_en timestamptz not null default now(),
    primary key (usuario_id, version_politica)
);

-- Índices de lectura y de integridad referencial.
