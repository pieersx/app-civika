-- Funciones internas. Viven en un esquema no expuesto por PostgREST.
create schema if not exists private;
grant usage on schema private to anon, authenticated;

create or replace function private.rol_actual()
returns public.rol
language sql
stable
security definer
set search_path = ''
as $$
    select u.rol
    from public.usuarios u
    where u.id = auth.uid() and u.activo
$$;

create or replace function private.entidad_actual()
returns integer
language sql
stable
security definer
set search_path = ''
as $$
    select u.entidad_id
    from public.usuarios u
    where u.id = auth.uid() and u.activo
$$;

create or replace function private.aal2()
returns boolean
language sql
stable
set search_path = ''
as $$
    select coalesce(auth.jwt() ->> 'aal', '') = 'aal2'
$$;

revoke execute on function private.rol_actual() from public;
revoke execute on function private.entidad_actual() from public;
revoke execute on function private.aal2() from public;
grant execute on function private.rol_actual() to anon, authenticated;
grant execute on function private.entidad_actual() to anon, authenticated;
grant execute on function private.aal2() to authenticated;

create or replace function private.calcular_prioridad(
    p_categoria_id integer,
    p_apoyos integer,
    p_creado_en timestamptz
)
returns integer
language sql
stable
set search_path = ''
as $$
    select
        c.peso_prioridad * 10
        + least(greatest(coalesce(p_apoyos, 0), 0), 50)
        + greatest(
            (timezone('America/Lima', now()))::date
            - (timezone('America/Lima', p_creado_en))::date,
            0
        ) * 2
        + case
            when (
                (timezone('America/Lima', now()))::date
                - (timezone('America/Lima', p_creado_en))::date
            ) > c.plazo_objetivo_dias
            then 20
            else 0
          end
    from public.categorias c
    where c.id = p_categoria_id
$$;

create or replace function private.set_prioridad()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.prioridad := private.calcular_prioridad(new.categoria_id, new.apoyos_count, new.creado_en);
    return new;
end;
$$;

create or replace function private.incrementar_version()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    if new.status is distinct from old.status then
        new.version := old.version + 1;
    end if;
    return new;
end;
$$;

create or replace function private.recalcular_prioridad(p_incidente_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_apoyos integer;
begin
    select count(*) into v_apoyos
    from public.apoyos a
    where a.incidente_id = p_incidente_id;

    update public.incidentes i
    set apoyos_count = v_apoyos,
        prioridad = private.calcular_prioridad(i.categoria_id, v_apoyos, i.creado_en)
    where i.id = p_incidente_id;
end;
$$;

create or replace function private.on_apoyo_cambiado()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    if tg_op = 'DELETE' then
        perform private.recalcular_prioridad(old.incidente_id);
        return old;
    end if;
    perform private.recalcular_prioridad(new.incidente_id);
    return new;
end;
$$;

create or replace function private.proteger_campos_usuario()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    if current_user not in ('postgres', 'service_role', 'supabase_admin')
       and (
           new.rol is distinct from old.rol
           or new.entidad_id is distinct from old.entidad_id
           or new.activo is distinct from old.activo
       )
    then
        raise exception 'Solo el administrador puede cambiar rol, entidad o estado de la cuenta'
            using errcode = '42501';
    end if;
    return new;
end;
$$;

create or replace function private.auditar_usuario()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    if new.rol is distinct from old.rol
       or new.entidad_id is distinct from old.entidad_id
       or new.activo is distinct from old.activo
    then
        insert into public.auditoria (actor_id, accion, objeto, antes, despues)
        values (
            auth.uid(),
            'usuario_actualizado',
            'usuarios:' || new.id::text,
            jsonb_build_object('rol', old.rol, 'entidad_id', old.entidad_id, 'activo', old.activo),
            jsonb_build_object('rol', new.rol, 'entidad_id', new.entidad_id, 'activo', new.activo)
        );
    end if;
    return new;
end;
$$;

create or replace function private.auditar_foto()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    if new.oculta is distinct from old.oculta and new.oculta then
        insert into public.auditoria (actor_id, accion, objeto, antes, despues)
        values (
            auth.uid(),
            'foto_oculta',
            'fotos:' || new.id::text,
            jsonb_build_object('oculta', old.oculta),
            jsonb_build_object('oculta', new.oculta)
        );
    end if;
    return new;
end;
$$;

create or replace function private.auditar_rechazo()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    if new.estado_nuevo = 'rechazado' then
        insert into public.auditoria (actor_id, accion, objeto, antes, despues)
        values (
            new.autor_id,
            'reporte_rechazado',
            'incidentes:' || new.incidente_id::text,
            jsonb_build_object('estado', new.estado_anterior),
            jsonb_build_object('estado', new.estado_nuevo)
        );
    end if;
    return new;
end;
$$;

create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    insert into public.usuarios (id, nombre)
    values (
        new.id,
        coalesce(nullif(new.raw_user_meta_data ->> 'nombre', ''), 'Ciudadano')
    )
    on conflict (id) do nothing;
    return new;
end;
$$;

create or replace function private.validar_fotos(p_fotos text[])
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_foto text;
    v_uid text;
begin
    if p_fotos is null or cardinality(p_fotos) = 0 then
        raise exception 'El reporte necesita al menos una foto' using errcode = '22023';
    end if;
    if cardinality(p_fotos) > 3 then
        raise exception 'Máximo 3 fotos por reporte' using errcode = '22023';
    end if;
    if cardinality(p_fotos) <> (select count(distinct x) from unnest(p_fotos) x) then
        raise exception 'No se puede repetir la misma foto' using errcode = '22023';
    end if;

    v_uid := auth.uid()::text;
    foreach v_foto in array p_fotos loop
        if v_uid is null or v_foto not like v_uid || '/%' then
            raise exception 'Cada foto debe estar en la carpeta del usuario' using errcode = '42501';
        end if;
        if not exists (
            select 1
            from storage.objects o
            where o.bucket_id = 'fotos' and o.name = v_foto
        ) then
            raise exception 'La foto % no existe en Storage', v_foto using errcode = '22023';
        end if;
    end loop;
end;
$$;

create or replace function private.transicion_permitida(
    p_desde public.estado,
    p_hacia public.estado,
    p_rol public.rol
)
returns boolean
language sql
immutable
set search_path = ''
as $$
    select case
        when p_rol = 'entidad' and p_desde = 'derivado' and p_hacia = 'en_revision' then true
        when p_rol = 'entidad' and p_desde = 'derivado' and p_hacia = 'en_atencion' then true
        when p_rol = 'entidad' and p_desde = 'en_atencion' and p_hacia = 'en_revision' then true
        when p_rol = 'entidad' and p_desde = 'en_atencion' and p_hacia = 'resuelto' then true
        when p_rol = 'moderador' and p_desde = 'en_revision' and p_hacia = 'derivado' then true
        when p_rol = 'moderador' and p_desde = 'en_revision' and p_hacia = 'rechazado' then true
        else false
    end
$$;

-- Triggers de integridad y trazabilidad.
create trigger usuarios_proteger_campos
before update on public.usuarios
for each row execute function private.proteger_campos_usuario();

create trigger usuarios_auditar_campos
after update on public.usuarios
for each row execute function private.auditar_usuario();

create trigger fotos_auditar_ocultamiento
after update of oculta on public.fotos
for each row execute function private.auditar_foto();

create trigger historial_auditar_rechazo
after insert on public.historial_estados
for each row execute function private.auditar_rechazo();

create trigger incidentes_prioridad
before insert or update on public.incidentes
for each row execute function private.set_prioridad();

create trigger incidentes_version
before update of status on public.incidentes
for each row execute function private.incrementar_version();

create trigger apoyos_recalcular
after insert or delete on public.apoyos
for each row execute function private.on_apoyo_cambiado();

-- El alta en auth.users crea la fila pública. El nombre es un dato de perfil, no de autorización.
create trigger on_auth_user_created
after insert on auth.users
for each row execute function private.handle_new_user();

